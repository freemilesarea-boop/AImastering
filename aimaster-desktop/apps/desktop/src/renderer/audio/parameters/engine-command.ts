// ── Logging helpers (for the dev / Storybook command log view) ──────────

/**
 * Compact single-line representation of a command for the log view.
 *
 * Example: "user · SET_MODULE_PARAM eq.lowShelfDb = 3.5 dB (clamped from 8 dB)"
 */
export function describeCommand(cmd: EngineCommand): string {
  const ts = cmd.timestamp.toFixed(0);
  switch (cmd.kind) {
    case 'SET_MODULE_PARAM': {
      const v = JSON.stringify(cmd.value);
      const tag =
        cmd.validation.status === 'ok' ? '' :
        cmd.validation.status === 'clamped' ?
          ` (clamped from ${JSON.stringify(cmd.validation.from)})` :
          ` (rejected: ${cmd.validation.reason})`;
      return `[${ts}] ${cmd.source} · SET ${cmd.moduleId}.${cmd.parameterId} = ${v}${tag}`;
    }
    case 'SET_MODULE_BYPASS':
      return `[${ts}] ${cmd.source} · BYPASS ${cmd.moduleId} = ${cmd.bypass}`;
    case 'RESET_MODULE':
      return `[${ts}] ${cmd.source} · RESET ${cmd.moduleId}`;
    case 'LOAD_PRESET':
      return `[${ts}] ${cmd.source} · LOAD_PRESET ${cmd.presetId}`;
    case 'APPLY_REFERENCE_PROFILE':
      return `[${ts}] ${cmd.source} · APPLY_REFERENCE_PROFILE ${cmd.profileId}`;
    case 'EXPORT_DESCRIPTOR_UPDATE':
      return `[${ts}] ${cmd.source} · EXPORT_DESCRIPTOR ${JSON.stringify(cmd.descriptor)}`;
  }
}
