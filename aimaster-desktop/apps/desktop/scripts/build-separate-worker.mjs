// Bundle the separator's worker into the renderer's public directory.
//
// It has to be one self-contained classic script, because `run.ts` fetches it
// as text and constructs a Worker from a Blob — the only route that works both
// under the dev server and in a packaged build served from `file://`.  A module
// worker would need to resolve imports at runtime, and a `file://` document
// cannot.
//
//   node scripts/build-separate-worker.mjs           build it
//   node scripts/build-separate-worker.mjs --check   fail if it is out of date
//
// The output is committed, so `pnpm dev` works without anyone remembering to
// run this.  `--check` is what stops a committed copy from drifting away from
// the TypeScript it was built from — `pnpm test:separate` runs it.

import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(desktop, 'src/renderer/daw/audio/separate/worker-entry.ts');
const out = path.join(desktop, 'src/renderer/public/separate.worker.js');
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  // Readable on purpose: this is the one file in the app a user could open in
  // a text editor to see what the separator is doing to their audio.
  minify: false,
  legalComments: 'inline',
  write: false,
  banner: {
    js: '// GENERATED by scripts/build-separate-worker.mjs — edit the TypeScript in\n'
      + '// src/renderer/daw/audio/separate/ and rebuild.  `pnpm test:separate`\n'
      + '// fails if this file and that TypeScript have drifted apart.\n',
  },
});

const built = result.outputFiles?.[0]?.text ?? '';
const existing = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;

if (check) {
  if (existing === built) {
    console.log(`separate.worker.js is current (${(built.length / 1024).toFixed(0)} KB)`);
    process.exit(0);
  }
  console.error(existing === null
    ? `${out} 이 없습니다 — node scripts/build-separate-worker.mjs 를 실행하세요.`
    : `${out} 이(가) TypeScript 원본과 다릅니다 — node scripts/build-separate-worker.mjs 를 실행하세요.`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, built);
console.log(`${path.relative(desktop, out)}  ${(built.length / 1024).toFixed(0)} KB`
  + (existing === built ? '  (unchanged)' : ''));
