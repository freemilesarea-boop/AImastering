// Bundle the model runner's worker into the renderer's public directory.
//
// One self-contained CLASSIC script, same as the separator's worker and for
// the same reason: `run.ts` fetches it as text and constructs a Worker from a
// Blob, which is the only route that works both under the dev server and in a
// packaged build served from `file://`.
//
// The difference is what is inside.  This one bundles `onnxruntime-web/wasm`,
// which was measured at 71 KB as an IIFE with zero esbuild warnings — that
// measurement is the whole reason a MODULE worker turned out to be
// unnecessary.  The runtime's own 12.86 MB `.wasm` is NOT in here; it is read
// by the main process and handed over as bytes at run time.
//
//   node scripts/build-model-worker.mjs           build it
//   node scripts/build-model-worker.mjs --check   fail if it is out of date
//
// The output is committed so `pnpm dev` works without anyone remembering to
// run this, and `--check` is what stops the committed copy from drifting away
// from the TypeScript it was built from — `pnpm test:model-dispatch` runs it.

import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const desktop = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(desktop, 'src/renderer/daw/audio/separate/model-worker-entry.ts');
const out = path.join(desktop, 'src/renderer/public/model.worker.js');
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  // Minified, unlike the separator's worker.  That one is readable on purpose
  // because a user could want to see what the app is doing to their audio;
  // most of this file is a vendored runtime, and leaving it unminified would
  // be half a megabyte of somebody else's code pretending to be readable.
  minify: true,
  legalComments: 'inline',
  write: false,
  banner: {
    js: '// GENERATED by scripts/build-model-worker.mjs — edit the TypeScript in\n'
      + '// src/renderer/daw/audio/separate/ and rebuild.  `pnpm test:model-dispatch`\n'
      + '// fails if this file and that TypeScript have drifted apart.\n',
  },
});

if (result.warnings.length > 0) {
  // Warnings here are how the bundling assumption would fail: an `import.meta`
  // that cannot be expressed in IIFE, a dynamic import left unresolved.
  for (const w of result.warnings) console.error(`  warn: ${w.text}`);
  console.error('esbuild warned while bundling the runtime — do not ship this silently.');
  process.exit(1);
}

const built = result.outputFiles?.[0]?.text ?? '';
const existing = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;

if (check) {
  if (existing === built) {
    console.log(`model.worker.js is current (${(built.length / 1024).toFixed(0)} KB)`);
    process.exit(0);
  }
  console.error(existing === null
    ? `${out} 이 없습니다 — node scripts/build-model-worker.mjs 를 실행하세요.`
    : `${out} 이(가) TypeScript 원본과 다릅니다 — node scripts/build-model-worker.mjs 를 실행하세요.`);
  process.exit(1);
}

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, built);
console.log(`${path.relative(desktop, out)}  ${(built.length / 1024).toFixed(0)} KB`);
